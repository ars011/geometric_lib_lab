def area(a, b): 
    '''
    принимает a,b
    a (int) - сторона прямоугольника
    b (int) - вторая сторона прямоугольнмка
    возвращает площадь прямоугольника
    '''
    return a * b 

def perimeter(a, b): 
    '''
    принимает a,b
    a (int) - сторона прямоугольника
    b (int) - вторая сторона прямоугольнмка
    возвращать периметр прямоугольника
    '''
    return 2 * (a + b)
