def area(a, h): 
    '''
    принимает a и h 
    a - основание треугольника
    h - высота треугольника
    возвращает площадь треугольника
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    принимает a,b,c
    a - сторона треугольника
    b - вторая сторона треугольника
    c - третяя сторона треугольника
    возвращает периметр треугольника
    '''
    return a + b + c 
